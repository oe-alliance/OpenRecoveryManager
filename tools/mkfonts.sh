#!/bin/sh
# Builds the fonts of the LVGL interface, src/fonts/orm_font.c: DejaVu Sans and the icons of the menu, reduced to
# the characters of the texts, which LVGL's Tiny TTF renders in the size of the screen, see tools/fonts/README.md.
#
#   tools/mkfonts.sh
#
# Needs Python with fontTools (pip install fonttools) on the host, not in the image; PYTHON names another
# interpreter than python3.
set -e
cd "$(dirname "$0")/.."

# DejaVu Sans: ASCII, Latin-1, Latin Extended-A, modern Greek and Cyrillic, Arabic and Persian with the forms LVGL joins, typographic punctuation, arrows and a few symbols
# (U+2328 keyboard for remote support, check, cross, warning, play).
TEXT="20-7E,A0-17F,384-38A,38C,38E-3A1,3A3-3CE,400-45F,490-491,60C,61B,61F,621-652,660-669,67E,686,698,6A9,6AF,6CC,FB56-FB59,FB7A-FB7D,FB8A-FB8B,FB8E-FB95,FBFC-FBFF,FE70-FEFC,2013-2014,2018-201A,201C-201E,2022,2026,2190-2193,2328,2713,2717,26A0,25B6"
# Font Awesome icons of the menu: rotate-right, file-lines, paper-plane, puzzle-piece, cloud-arrow-down,
# sliders, life-ring, microchip, layer-group, headset, circle-info, right-from-bracket.
ICONS="F2F9,F15C,F1D8,F12E,F0ED,F1DE,F1CD,F2DB,F5FD,F590,F05A,F2F5"

mkdir -p src/fonts
"${PYTHON:-python3}" -m fontTools.subset tools/fonts/DejaVuSans.ttf --unicodes="$TEXT" --layout-features=kern --no-hinting \
	--desubroutinize --output-file=src/fonts/orm_font.ttf
"${PYTHON:-python3}" -m fontTools.subset tools/fonts/fontawesome/fa-solid-900.ttf --unicodes="$ICONS" --layout-features= \
	--name-IDs= --no-hinting --desubroutinize --output-file=src/fonts/orm_icons.ttf  # Without the Reserved Font Name.
"${PYTHON:-python3}" - <<'PY'
def array(out, name, path):
	data = open(path, "rb").read()
	out.write("const unsigned char %s[] = {\n" % name)
	for i in range(0, len(data), 16):
		out.write("\t" + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
	out.write("};\n")
	out.write("const size_t %s_size = sizeof(%s);\n" % (name, name))

with open("src/fonts/orm_font.c", "w", newline="\n") as out:
	out.write("/* Generated by tools/mkfonts.sh, do not edit. DejaVu Sans 2.37 (Bitstream Vera and Arev licenses,\n")
	out.write(" * tools/fonts/DejaVuSans-LICENSE.txt) and icons of Font Awesome 7.3.1 Free Solid (SIL OFL 1.1,\n")
	out.write(" * tools/fonts/fontawesome/LICENSE.txt), reduced to the characters of the texts. */\n")
	out.write("#include <stddef.h>\n\n")
	array(out, "orm_font_ttf", "src/fonts/orm_font.ttf")
	out.write("\n")
	array(out, "orm_icons_ttf", "src/fonts/orm_icons.ttf")
PY
rm src/fonts/orm_font.ttf src/fonts/orm_icons.ttf
